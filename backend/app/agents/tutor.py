"""Tutor agent: the live-session orchestrator's decision/content logic.

Two responsibilities, kept deliberately separate from the WebSocket/DB
plumbing (that lives in the session service, spec section 7/8):

1. Rendering a Lesson Plan beat (pre-generated by CurriculumDesigner during
   the async research pipeline) into a spoken utterance -- reading, not
   improvising, per spec section 4's core latency-regime split.
2. The "I don't understand" escalation ladder state machine (spec risk
   A.4 / section 7): simpler_explanation -> analogy -> example ->
   counterexample -> diagnostic_question -> exhausted (mark for later
   return). Only escalation content needs a live LLM call, since the
   Lesson Plan only scripts one explanation, not five fallback framings.

Every piece of learner-facing text produced here passes through
`enforce_length_limit` before being returned -- the hard "never more than
a few sentences before handing back the turn" rule is enforced here in
code, not left to the system prompt (spec section 1/7).
"""

from enum import Enum

from app.agents.text_limits import enforce_length_limit
from app.core.config import get_settings
from app.integrations.anthropic_client import AnthropicClient, ModelTier
from app.models.models import TurnType
from app.schemas.research import locale_name
from app.schemas.session import EscalationRung as EscalationRungSchema

MAX_ESCALATION_ATTEMPTS = 5


class EscalationRung(str, Enum):
    simpler_explanation = "simpler_explanation"
    analogy = "analogy"
    example = "example"
    counterexample = "counterexample"
    diagnostic_question = "diagnostic_question"
    exhausted = "exhausted"  # terminal: mark_for_later_return


_ESCALATION_ORDER = [
    EscalationRung.simpler_explanation,
    EscalationRung.analogy,
    EscalationRung.example,
    EscalationRung.counterexample,
    EscalationRung.diagnostic_question,
]

_ESCALATION_INSTRUCTIONS = {
    EscalationRung.simpler_explanation: (
        "Re-explain the concept in simpler words than before -- shorter sentences, "
        "everyday vocabulary, no jargon."
    ),
    EscalationRung.analogy: "Explain the concept using a relatable analogy to something everyday.",
    EscalationRung.example: "Give one concrete, specific example that illustrates the concept in action.",
    EscalationRung.counterexample: (
        "Give one counterexample or edge case -- something that looks similar but is NOT this "
        "concept -- to sharpen the boundary of what it means."
    ),
    EscalationRung.diagnostic_question: (
        "Ask one small, easy diagnostic question to figure out exactly which part is unclear "
        "(not the original question again -- something more targeted/simpler)."
    ),
}

_ESCALATION_SYSTEM = """You are a patient voice tutor. The learner did not understand your \
previous explanation of a concept. {instruction}

Keep it to at most 3 short sentences (this will be spoken aloud). Write in {locale}."""


def next_escalation_rung(current: EscalationRung | None) -> EscalationRung:
    if current is None:
        return _ESCALATION_ORDER[0]
    if current not in _ESCALATION_ORDER:
        return EscalationRung.exhausted
    idx = _ESCALATION_ORDER.index(current)
    if idx + 1 >= len(_ESCALATION_ORDER):
        return EscalationRung.exhausted
    return _ESCALATION_ORDER[idx + 1]


class Tutor:
    def __init__(self, client: AnthropicClient):
        self._client = client
        self._settings = get_settings()

    def enforce_length(self, text: str) -> str:
        return enforce_length_limit(
            text,
            max_sentences=self._settings.tutor_max_sentences,
            max_chars=self._settings.tutor_max_chars,
        )

    def render_beat(self, beat_type: str, content: dict) -> tuple[TurnType, str]:
        """Deterministically turns a lesson_plan_beats row into (turn_type,
        utterance_text). No LLM call -- this is exactly the "tutor reads
        from the pre-built lesson" path."""
        if beat_type in ("explain", "transition"):
            return TurnType.explain if beat_type == "explain" else TurnType.transition, self.enforce_length(
                content.get("text", "")
            )
        if beat_type == "question":
            return TurnType.question, self.enforce_length(content.get("text", ""))
        if beat_type == "expected_answer_rubric":
            # Not spoken directly -- used by Quizmaster for grading.
            return TurnType.checkin, ""
        if beat_type == "follow_up":
            return TurnType.feedback, ""
        return TurnType.explain, self.enforce_length(content.get("text", ""))

    async def generate_escalation_text(
        self,
        concept_name: str,
        concept_definition: str,
        rung: EscalationRung,
        locale: str = "pl",
        *,
        topic_id=None,
        session_id=None,
    ) -> str:
        if rung == EscalationRung.exhausted:
            raise ValueError("Cannot generate text for the terminal 'exhausted' rung")

        result: EscalationRungSchema = await self._client.structured_call(
            agent_name=f"tutor.escalation.{rung.value}",
            tier=ModelTier.sonnet,
            system=_ESCALATION_SYSTEM.format(
                instruction=_ESCALATION_INSTRUCTIONS[rung], locale=locale_name(locale)
            ),
            user_message=f"Concept: {concept_name}\nDefinition: {concept_definition}",
            response_model=EscalationRungSchema,
            topic_id=topic_id,
            session_id=session_id,
        )
        return self.enforce_length(result.text)
